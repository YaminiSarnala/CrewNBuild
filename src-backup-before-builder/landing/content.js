// Roles still in development send visitors to the coming-soon page rather than sign-up.
export function roleDestination(key) {
  const role = roleMeta.find((entry) => entry.key === key);
  // Web returned a URL string; navigation here takes a screen + params.
  return role?.comingSoon
    ? { screen: "ComingSoon", params: { role: key } }
    : { screen: "Signup", params: { role: key } };
}

export function isUpcomingRole(key) {
  return roleMeta.some((role) => role.key === key && role.comingSoon);
}

